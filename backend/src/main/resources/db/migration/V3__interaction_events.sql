-- Append-only engagement log: the training data for a future learned ranker, and an input to
-- online features (clicks feed author affinity, impressions drive the already-seen filter).
CREATE TABLE interaction_events (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    post_id         BIGINT      NOT NULL, -- no FK: events outlive deleted posts for training
    type            VARCHAR(20) NOT NULL, -- IMPRESSION, CLICK, DWELL, LIKE, REPOST, REPLY
    surface         VARCHAR(20),          -- FOR_YOU, FOLLOWING, PROFILE, POST
    rank_position   INTEGER,
    dwell_ms        INTEGER,
    model_version   VARCHAR(40),
    outbox_event_id BIGINT UNIQUE,        -- dedupes server-side events on outbox redelivery
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX interaction_user_type_idx ON interaction_events (user_id, type, post_id);
