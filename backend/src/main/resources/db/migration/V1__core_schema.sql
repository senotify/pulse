-- Pulse core schema: identity, social graph, posts, engagement, transactional outbox.
-- Kept to SQL that runs on PostgreSQL and on H2 in PostgreSQL mode (used by tests).

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(20)  NOT NULL UNIQUE,  -- stored lowercased
    email         VARCHAR(254) NOT NULL UNIQUE,  -- stored lowercased
    display_name  VARCHAR(50)  NOT NULL,
    bio           VARCHAR(160) NOT NULL DEFAULT '',
    password_hash VARCHAR(100) NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE follows (
    follower_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    followee_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (follower_id, followee_id),
    CONSTRAINT follows_not_self CHECK (follower_id <> followee_id)
);
CREATE INDEX follows_followee_idx ON follows (followee_id, follower_id);

CREATE TABLE blocks (
    blocker_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    blocked_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (blocker_id, blocked_id),
    CONSTRAINT blocks_not_self CHECK (blocker_id <> blocked_id)
);
CREATE INDEX blocks_blocked_idx ON blocks (blocked_id, blocker_id);

CREATE TABLE mutes (
    muter_id   BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    muted_id   BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (muter_id, muted_id),
    CONSTRAINT mutes_not_self CHECK (muter_id <> muted_id)
);

-- A post is either an original/reply (content set) or a repost (repost_of_id set, no content).
CREATE TABLE posts (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id    BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    content      VARCHAR(280),
    reply_to_id  BIGINT REFERENCES posts (id) ON DELETE SET NULL,
    repost_of_id BIGINT REFERENCES posts (id) ON DELETE CASCADE,
    like_count   INTEGER NOT NULL DEFAULT 0,
    reply_count  INTEGER NOT NULL DEFAULT 0,
    repost_count INTEGER NOT NULL DEFAULT 0,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT posts_kind_chk CHECK (
        (repost_of_id IS NULL AND content IS NOT NULL)
        OR (repost_of_id IS NOT NULL AND content IS NULL AND reply_to_id IS NULL)
    ),
    CONSTRAINT posts_one_repost_uq UNIQUE (author_id, repost_of_id)
);
CREATE INDEX posts_author_idx ON posts (author_id, id);
CREATE INDEX posts_reply_idx ON posts (reply_to_id, id);
CREATE INDEX posts_repost_idx ON posts (repost_of_id);

CREATE TABLE likes (
    user_id    BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    post_id    BIGINT NOT NULL REFERENCES posts (id) ON DELETE CASCADE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, post_id)
);
CREATE INDEX likes_post_idx ON likes (post_id);

-- Domain events written in the same transaction as the state change.
-- A relay (in-process now, Debezium/Kafka in the scale-out topology) publishes them.
CREATE TABLE outbox_events (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aggregate_type VARCHAR(40) NOT NULL,
    aggregate_id   BIGINT      NOT NULL,
    event_type     VARCHAR(60) NOT NULL,
    payload        TEXT        NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    published_at   TIMESTAMP WITH TIME ZONE
);
CREATE INDEX outbox_pending_idx ON outbox_events (published_at, id);
